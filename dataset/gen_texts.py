"""Тексты для датасета голоса Мики: локальная LLM пишет реплики в её манере на разные темы.
Пишет dataset/texts.txt, по реплике на строку; повторный запуск дописывает недостающее."""
import json, os, random, re, sys
import httpx

LLM_URL = os.environ["LLM_URL"]
OUT = os.path.join(os.path.dirname(__file__), "texts.txt")
TARGET = int(sys.argv[1]) if len(sys.argv) > 1 else 900

TOPICS = [
    "космос и звёзды", "еда и готовка", "кино и сериалы", "аниме и манга", "музыка", "игры", "погода и времена года",
    "путешествия", "животные", "учёба и школа", "работа и усталость", "программирование и компьютеры", "спорт",
    "сон и утро", "книги", "мечты и планы", "друзья и отношения", "грусть и поддержка собеседника", "шутки и подколки",
    "наука и техника", "история", "природа и лес", "город и транспорт", "праздники", "одежда и стиль", "здоровье",
    "деньги и покупки", "хобби и рукоделие", "море и пляж", "тело аватара Мики: она машет, танцует, кивает",
    "приветствия и прощания", "вопросы собеседнику о его дне", "удивление и восторг", "сомнение и раздумья",
    "извинения и неловкость", "объяснение чего-то сложного простыми словами",
]
STYLES = [
    "короткие живые реакции из одного–четырёх слов (угу, ой, правда?, вот это да, ну-у, хм)",
    "обычные разговорные реплики из одного предложения",
    "реплики из двух–трёх предложений, с вопросом собеседнику",
    "длинные увлечённые объяснения в одно-два длинных предложения с запятыми и тире",
    "эмоциональные восклицания: радость, смех, удивление, возмущение в шутку",
    "задумчивые и мягкие реплики, с паузами через многоточие",
    "реплики, где есть числа, даты, время, проценты — числа писать словами",
    "реплики с редкими, длинными и трудными для произношения русскими словами",
]
PROMPT = """Ты помогаешь собрать датасет для синтеза речи. Голос — Мика, живая, тёплая и немного озорная аниме-девушка, которая болтает с собеседником голосом.
Напиши {n} разных реплик Мики. Тема: {topic}. Вид реплик: {style}.
Правила:
- только то, что Мика произносит вслух, от первого лица, женский род;
- естественная разговорная русская речь, без канцелярита;
- всегда пиши букву ё там, где она нужна;
- числа, даты, сокращения — словами, как их произносят; без латиницы, цифр, эмодзи, скобок и кавычек-ёлочек внутри;
- каждая реплика заканчивается знаком препинания: точкой, восклицательным, вопросительным знаком или многоточием; внутри — нормальная пунктуация;
- смех не пиши буквами (никаких «хаха»), междометия — только произносимые;
- реплики грамотные: проверь род, падежи и даты;
- реплики не повторяют друг друга и не начинаются одинаково.
Ответ — только JSON-массив строк."""

have = []
if os.path.exists(OUT):
    have = [l.strip() for l in open(OUT, encoding="utf-8") if l.strip()]
seen = {re.sub(r"\W+", " ", l.lower()).strip() for l in have}
client = httpx.Client(timeout=300, trust_env=False)  # в обход системного прокси: LLM в локалке
rng = random.Random(len(have))
bad_chars = re.compile(r"[A-Za-z0-9\[\]{}<>«»\"*#@_/\\|~^$%&=+]")

with open(OUT, "a", encoding="utf-8") as f:
    while len(have) < TARGET:
        topic, style = rng.choice(TOPICS), STYLES[int(os.environ["STYLE"])] if "STYLE" in os.environ else rng.choice(STYLES)
        body = {"messages": [{"role": "user", "content": PROMPT.format(n=20, topic=topic, style=style)}],
                "max_tokens": 3000, "temperature": 0.95, "reasoning_effort": "none"}
        try:
            text = client.post(LLM_URL, json=body).json()["choices"][0]["message"]["content"]
            lines = json.loads(text[text.index("["): text.rindex("]") + 1])
        except Exception as e:
            print("пропуск:", repr(e)[:200], flush=True)
            continue
        added = 0
        for l in lines:
            l = re.sub(r"\s+", " ", str(l)).strip()
            key = re.sub(r"\W+", " ", l.lower()).strip()
            if (not l or len(l) > 260 or bad_chars.search(l) or key in seen or not re.search(r"[.!?…]$", l)
                    or re.search(r"(?i)\b(ха){2,}|хах", l)):
                continue
            seen.add(key); have.append(l); added += 1
            f.write(l + "\n")
        f.flush()
        print(f"{len(have)}/{TARGET}  +{added}  {topic} / {style[:40]}", flush=True)
